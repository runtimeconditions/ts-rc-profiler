const FIXTURES = fileURLToPath(new URL("../../test/fixtures/", import.meta.url));
const COMMON = "node_modules/@runtimeconditions/common-integrations";
const ENV = "node_modules/@runtimeconditions/env-configuration";

function invoke(args: string[]): { code: number; out: string; err: string } {
  let out = "";
  let err = "";
  const code = run(args, { out: (text) => (out += text), err: (text) => (err += text) });
  return { code, out, err };
}

function generate(project: string, extra: string[] = [], name = "workload") {
  return invoke(["profile", "generate", "--project", project, "--name", name, "--workload-uri", `https://services.example.com/${name}`, ...extra]);
}

function fixture(workload: string): string {
  return join(FIXTURES, "workloads", workload);
}

function expected(name: string): string {
  return readFileSync(join(FIXTURES, "expected", `${name}.profile.yaml`), "utf-8");
}

function workspace(workload: string, modules = "node_modules"): { root: string; project: string } {
  const root = mkdtempSync(join(tmpdir(), "typescript-profiler-"));
  cpSync(join(FIXTURES, modules), join(root, "node_modules"), { recursive: true });
  const project = join(root, "project");
  cpSync(fixture(workload), project, { recursive: true });
  return { root, project };
}

function sha256(text: string): string {
  return createHash("sha256").update(text).digest("hex");
}

function rewrite(root: string, directory: string, relative: string, change: (text: string) => string): void {
  const path = join(root, directory, relative);
  const text = change(readFileSync(path, "utf-8"));
  writeFileSync(path, text);
  const listing = join(root, directory, "runtimeconditions.file-manifest.yaml");
  writeFileSync(listing, readFileSync(listing, "utf-8").replace(new RegExp(`(${relative.replace(/[.]/g, "\\.")}: )[0-9a-f]{64}`), `$1${sha256(text)}`));
}

