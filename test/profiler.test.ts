test("verify-bindings lists the closure and marks what the workload imports", () => {
  const cache = invoke(["profile", "verify-bindings", "--project", fixture("cache")]);
  assert.equal(cache.code, 0, cache.err);
  assert.match(cache.out, /^@runtimeconditions\/common-integrations@0\.1\.0 https:\/\/runtimeconditions\.io\/extensions\/common-integrations\//m);
  assert.match(cache.out, /^@runtimeconditions\/env-configuration@0\.1\.0 /m);
  assert.doesNotMatch(cache.out, /\(dependency\)/);

  const api = JSON.parse(invoke(["profile", "verify-bindings", "--project", fixture("api"), "--json"]).out);
  assert.deepEqual(
    api.bindings.map((item: any) => [item.package, item.direct]),
    [["@runtimeconditions/common-integrations", true]],
  );
});

